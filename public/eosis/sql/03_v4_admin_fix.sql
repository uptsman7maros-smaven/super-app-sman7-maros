CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =========================================================
-- 1. TABEL ADMIN TERPISAH
-- =========================================================
CREATE TABLE IF NOT EXISTS public.admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Salin akun admin lama dari pengaturan ke tabel admin baru.
-- Password lama dipertahankan sebagai hash agar login lama tidak berubah.
INSERT INTO public.admin_users (username, password_hash)
SELECT TRIM(p.admin_username), p.admin_password
FROM public.pengaturan p
WHERE NULLIF(TRIM(p.admin_username), '') IS NOT NULL
  AND NULLIF(TRIM(p.admin_password), '') IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM public.admin_users a
    WHERE a.username = TRIM(p.admin_username)
  )
ORDER BY p.id
LIMIT 1;

REVOKE ALL ON TABLE public.admin_users FROM anon, authenticated;

-- =========================================================
-- 2. VALIDASI ADMIN: akun baru + kompatibilitas akun lama
-- =========================================================
CREATE OR REPLACE FUNCTION public.eosis_is_admin(
  p_username TEXT,
  p_password TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_valid BOOLEAN := FALSE;
BEGIN
  SELECT EXISTS (
    SELECT 1
    FROM public.admin_users a
    WHERE a.username = TRIM(p_username)
      AND (
        a.password_hash = crypt(p_password, a.password_hash)
        OR a.password_hash = p_password
      )
  ) INTO v_valid;

  IF v_valid THEN
    RETURN TRUE;
  END IF;

  -- Fallback akun lama dari tabel pengaturan.
  SELECT EXISTS (
    SELECT 1
    FROM public.pengaturan p
    WHERE TRIM(p.admin_username) = TRIM(p_username)
      AND (
        p.admin_password = crypt(p_password, p.admin_password)
        OR p.admin_password = p_password
      )
  ) INTO v_valid;

  RETURN COALESCE(v_valid, FALSE);
END;
$$;

-- =========================================================
-- 3. LOGIN ADMIN YANG EKSPLISIT
-- =========================================================
DROP FUNCTION IF EXISTS public.admin_login(TEXT,TEXT);
CREATE FUNCTION public.admin_login(
  p_username TEXT,
  p_password TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN public.eosis_is_admin(p_username, p_password);
END;
$$;

-- =========================================================
-- 4. GANTI USERNAME/PASSWORD ADMIN YANG SEDANG LOGIN
-- =========================================================
CREATE OR REPLACE FUNCTION public.update_admin_credentials_v3(
  p_username TEXT,
  p_password TEXT,
  p_new_username TEXT,
  p_new_password TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_old_id BIGINT;
  v_new_username TEXT;
BEGIN
  IF NOT public.eosis_is_admin(p_username, p_password) THEN
    RAISE EXCEPTION 'Username atau password admin lama salah';
  END IF;

  v_new_username := TRIM(p_new_username);

  IF NULLIF(v_new_username, '') IS NULL OR LENGTH(v_new_username) < 3 THEN
    RAISE EXCEPTION 'Username baru minimal 3 karakter.';
  END IF;

  IF p_new_password IS NULL OR LENGTH(p_new_password) < 6 THEN
    RAISE EXCEPTION 'Password baru minimal 6 karakter.';
  END IF;

  SELECT id INTO v_old_id
  FROM public.admin_users
  WHERE username = TRIM(p_username)
  LIMIT 1;

  IF EXISTS (
    SELECT 1 FROM public.admin_users
    WHERE username = v_new_username
      AND (v_old_id IS NULL OR id <> v_old_id)
  ) THEN
    RAISE EXCEPTION 'Username baru sudah digunakan admin lain.';
  END IF;

  IF v_old_id IS NOT NULL THEN
    UPDATE public.admin_users
    SET username = v_new_username,
        password_hash = crypt(p_new_password, gen_salt('bf'))
    WHERE id = v_old_id;
  ELSE
    INSERT INTO public.admin_users(username, password_hash)
    VALUES (v_new_username, crypt(p_new_password, gen_salt('bf')));
  END IF;

  -- Sinkronkan akun utama lama agar tetap kompatibel dengan fungsi lama.
  UPDATE public.pengaturan
  SET admin_username = v_new_username,
      admin_password = crypt(p_new_password, gen_salt('bf'))
  WHERE TRIM(admin_username) = TRIM(p_username)
     OR id = (SELECT id FROM public.pengaturan ORDER BY id LIMIT 1);

  RETURN TRUE;
END;
$$;

-- =========================================================
-- 5. TAMBAH ADMIN
-- =========================================================
CREATE OR REPLACE FUNCTION public.add_admin_v4(
  p_username TEXT,
  p_password TEXT,
  p_new_username TEXT,
  p_new_password TEXT
)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_name TEXT := TRIM(p_new_username);
  v_id BIGINT;
BEGIN
  IF NOT public.eosis_is_admin(p_username, p_password) THEN
    RAISE EXCEPTION 'Sesi admin tidak valid.';
  END IF;

  IF NULLIF(v_name, '') IS NULL OR LENGTH(v_name) < 3 THEN
    RAISE EXCEPTION 'Username admin minimal 3 karakter.';
  END IF;

  IF p_new_password IS NULL OR LENGTH(p_new_password) < 6 THEN
    RAISE EXCEPTION 'Password admin minimal 6 karakter.';
  END IF;

  IF EXISTS (SELECT 1 FROM public.admin_users WHERE username = v_name) THEN
    RAISE EXCEPTION 'Username admin sudah digunakan.';
  END IF;

  INSERT INTO public.admin_users(username, password_hash)
  VALUES (v_name, crypt(p_new_password, gen_salt('bf')))
  RETURNING id INTO v_id;

  RETURN json_build_object('id', v_id, 'username', v_name);
END;
$$;

-- =========================================================
-- 6. DAFTAR ADMIN
-- =========================================================
CREATE OR REPLACE FUNCTION public.get_admins_v4(
  p_username TEXT,
  p_password TEXT
)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.eosis_is_admin(p_username, p_password) THEN
    RAISE EXCEPTION 'Sesi admin tidak valid.';
  END IF;

  RETURN (
    SELECT COALESCE(
      json_agg(
        json_build_object(
          'id', a.id,
          'username', a.username,
          'created_at', a.created_at
        ) ORDER BY a.id
      ),
      '[]'::json
    )
    FROM public.admin_users a
  );
END;
$$;

-- =========================================================
-- 7. HAPUS ADMIN DENGAN PROTEKSI ADMIN TERAKHIR
-- =========================================================
CREATE OR REPLACE FUNCTION public.delete_admin_v4(
  p_username TEXT,
  p_password TEXT,
  p_id BIGINT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_count INTEGER;
  v_target_username TEXT;
BEGIN
  IF NOT public.eosis_is_admin(p_username, p_password) THEN
    RAISE EXCEPTION 'Sesi admin tidak valid.';
  END IF;

  SELECT COUNT(*) INTO v_count FROM public.admin_users;
  IF v_count <= 1 THEN
    RAISE EXCEPTION 'Admin terakhir tidak dapat dihapus.';
  END IF;

  SELECT username INTO v_target_username
  FROM public.admin_users
  WHERE id = p_id;

  IF v_target_username IS NULL THEN
    RAISE EXCEPTION 'Admin tidak ditemukan.';
  END IF;

  IF TRIM(v_target_username) = TRIM(p_username) THEN
    RAISE EXCEPTION 'Akun admin yang sedang digunakan tidak dapat dihapus. Gunakan akun admin lain.';
  END IF;

  DELETE FROM public.admin_users WHERE id = p_id;
  RETURN TRUE;
END;
$$;

-- =========================================================
-- 8. RESET PEMILIHAN: HASIL + STATUS SISWA + WAKTU MEMILIH
-- =========================================================
CREATE OR REPLACE FUNCTION public.reset_voting_results(
  p_username TEXT,
  p_password TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_votes INTEGER;
  v_students INTEGER;
BEGIN
  IF NOT public.eosis_is_admin(p_username, p_password) THEN
    RAISE EXCEPTION 'Username atau password admin salah';
  END IF;

  SELECT COUNT(*) INTO v_votes FROM public.suara;

  -- Hapus seluruh catatan suara anonim.
  DELETE FROM public.suara WHERE TRUE;

  -- Kembalikan agregat kandidat ke nol.
  UPDATE public.kandidat SET total_suara = 0 WHERE TRUE;

  -- Kembalikan seluruh hak suara dan waktu memilih.
  UPDATE public.siswa
  SET status_memilih = FALSE,
      waktu_memilih = NULL
  WHERE TRUE;

  SELECT COUNT(*) INTO v_students FROM public.siswa;

  RETURN TRUE;
END;
$$;

-- =========================================================
-- 9. SUBMIT VOTE: MENJAGA SINKRON SUARA <-> STATUS SISWA
-- =========================================================
CREATE OR REPLACE FUNCTION public.submit_vote(
  p_nisn TEXT,
  p_tgl_lahir DATE,
  p_kandidat_id BIGINT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_aktif BOOLEAN;
  v_student_id BIGINT;
  v_status BOOLEAN;
BEGIN
  SELECT COALESCE(pemilihan_aktif, TRUE)
  INTO v_aktif
  FROM public.pengaturan
  ORDER BY id
  LIMIT 1;

  IF COALESCE(v_aktif, TRUE) = FALSE THEN
    RAISE EXCEPTION 'Pemilihan sudah ditutup.';
  END IF;

  SELECT id, COALESCE(status_memilih, FALSE)
  INTO v_student_id, v_status
  FROM public.siswa
  WHERE TRIM(nisn) = TRIM(p_nisn)
    AND tgl_lahir = p_tgl_lahir
  FOR UPDATE;

  IF v_student_id IS NULL THEN
    RAISE EXCEPTION 'Data pemilih tidak ditemukan.';
  END IF;

  IF v_status THEN
    RAISE EXCEPTION 'Pemilih ini sudah menggunakan hak suara.';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.kandidat WHERE id = p_kandidat_id) THEN
    RAISE EXCEPTION 'Kandidat tidak ditemukan.';
  END IF;

  UPDATE public.siswa
  SET status_memilih = TRUE,
      waktu_memilih = NOW()
  WHERE id = v_student_id
    AND COALESCE(status_memilih, FALSE) = FALSE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Suara tidak dapat diproses. Silakan coba lagi.';
  END IF;

  INSERT INTO public.suara(kandidat_id) VALUES (p_kandidat_id);

  UPDATE public.kandidat
  SET total_suara = COALESCE(total_suara, 0) + 1
  WHERE id = p_kandidat_id;

  RETURN TRUE;
END;
$$;

-- =========================================================
-- 10. HEALTH CHECK: HARUS SAMA ANTARA SUARA DAN PEMILIH SUDAH MEMILIH
-- =========================================================
CREATE OR REPLACE FUNCTION public.get_system_sync_status_v3(
  p_username TEXT,
  p_password TEXT
)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_settings INTEGER;
  v_classes INTEGER;
  v_students INTEGER;
  v_candidates INTEGER;
  v_votes INTEGER;
  v_voted_students INTEGER;
  v_candidate_sum BIGINT;
BEGIN
  IF NOT public.eosis_is_admin(p_username, p_password) THEN
    RAISE EXCEPTION 'Username atau password admin salah';
  END IF;

  SELECT COUNT(*) INTO v_settings FROM public.pengaturan;
  SELECT COUNT(*) INTO v_classes FROM public.kelas;
  SELECT COUNT(*) INTO v_students FROM public.siswa;
  SELECT COUNT(*) INTO v_candidates FROM public.kandidat;
  SELECT COUNT(*) INTO v_votes FROM public.suara;
  SELECT COUNT(*) INTO v_voted_students FROM public.siswa WHERE COALESCE(status_memilih, FALSE) = TRUE;
  SELECT COALESCE(SUM(COALESCE(total_suara,0)),0) INTO v_candidate_sum FROM public.kandidat;

  RETURN json_build_object(
    'database_connected', TRUE,
    'pengaturan', v_settings,
    'kelas', v_classes,
    'siswa', v_students,
    'kandidat', v_candidates,
    'suara', v_votes,
    'siswa_sudah_memilih', v_voted_students,
    'total_suara_kandidat', v_candidate_sum,
    'sinkron_status', CASE
      WHEN v_votes = v_voted_students AND v_votes = v_candidate_sum THEN 'OK'
      ELSE 'PERLU CEK'
    END,
    'checked_at', NOW()
  );
END;
$$;

