CREATE OR REPLACE FUNCTION public.eosis_is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid()
      AND status = 'active'
      AND role IN ('super_admin', 'operator', 'kepala_sekolah')
  );
$$;

