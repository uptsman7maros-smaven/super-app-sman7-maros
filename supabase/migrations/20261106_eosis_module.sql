CREATE OR REPLACE FUNCTION public.submit_eosis_vote(p_candidate_id BIGINT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_voter public.eosis_voters%ROWTYPE;
  v_open BOOLEAN;
BEGIN
  SELECT v.* INTO v_voter
  FROM public.eosis_voters v
  JOIN public.profiles p ON p.username = v.nisn
  WHERE p.id = auth.uid();

  IF NOT FOUND THEN RAISE EXCEPTION 'Akun ini tidak terdaftar sebagai pemilih.'; END IF;
  SELECT voting_active INTO v_open FROM public.eosis_settings WHERE id = 1;
  IF NOT COALESCE(v_open, FALSE) THEN RAISE EXCEPTION 'Pemilihan sedang ditutup.'; END IF;
  IF v_voter.has_voted THEN RAISE EXCEPTION 'Hak suara sudah digunakan.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.eosis_candidates WHERE id = p_candidate_id) THEN
    RAISE EXCEPTION 'Kandidat tidak ditemukan.';
  END IF;

  INSERT INTO public.eosis_votes(voter_id, candidate_id) VALUES (v_voter.id, p_candidate_id);
  UPDATE public.eosis_voters SET has_voted = TRUE, voted_at = NOW() WHERE id = v_voter.id;
  UPDATE public.eosis_candidates SET vote_count = vote_count + 1 WHERE id = p_candidate_id;
  RETURN TRUE;
END;
$$;

REVOKE ALL ON FUNCTION public.submit_eosis_vote(BIGINT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.submit_eosis_vote(BIGINT) TO authenticated;

