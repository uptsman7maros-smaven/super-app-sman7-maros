create table if not exists public.datainduk_change_log (
  id bigint generated by default as identity primary key,
  changed_at timestamptz not null default clock_timestamp(),
  actor_id uuid references auth.users(id) on delete set null,
  actor_name text,
  table_name text not null check (table_name in ('students', 'teachers', 'classes')),
  record_id text not null,
  operation text not null check (operation in ('INSERT', 'UPDATE', 'DELETE')),
  changed_fields text[] not null default '{}',
  old_data jsonb,
  new_data jsonb
);

create index if not exists datainduk_change_log_changed_at_idx
  on public.datainduk_change_log (changed_at desc);
create index if not exists datainduk_change_log_record_idx
  on public.datainduk_change_log (table_name, record_id, changed_at desc);

alter table public.datainduk_change_log enable row level security;
revoke all on table public.datainduk_change_log from anon, authenticated;
grant select on table public.datainduk_change_log to authenticated;

drop policy if exists datainduk_change_log_admin_read
  on public.datainduk_change_log;
create policy datainduk_change_log_admin_read
  on public.datainduk_change_log
  for select to authenticated
  using (
    public.superapp_has_active_role(array['super_admin', 'operator']::text[])
  );

create or replace function public.datainduk_record_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old_data jsonb;
  v_new_data jsonb;
  v_record_id text;
  v_actor_id uuid := auth.uid();
  v_actor_name text;
  v_changed_fields text[];
begin
  if tg_op in ('UPDATE', 'DELETE') then
    v_old_data := to_jsonb(old);
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    v_new_data := to_jsonb(new);
  end if;

  if tg_op = 'UPDATE'
    and (v_old_data - 'updated_at') is not distinct from (v_new_data - 'updated_at')
  then
    return new;
  end if;

  if tg_op = 'UPDATE' then
    select coalesce(array_agg(field order by field), array[]::text[])
      into v_changed_fields
    from (
      select jsonb_object_keys(v_old_data) as field
      union
      select jsonb_object_keys(v_new_data) as field
    ) as fields
    where field <> 'updated_at'
      and (v_old_data -> field) is distinct from (v_new_data -> field);
  else
    select coalesce(array_agg(field order by field), array[]::text[])
      into v_changed_fields
    from jsonb_object_keys(coalesce(v_new_data, v_old_data)) as keys(field)
    where field not in ('id', 'created_at', 'updated_at');
  end if;

  if v_actor_id is not null then
    select coalesce(nullif(btrim(profile.full_name), ''), profile.username)
      into v_actor_name
    from public.profiles as profile
    where profile.id = v_actor_id;
  end if;

  v_record_id := coalesce(v_new_data ->> 'id', v_old_data ->> 'id');

  insert into public.datainduk_change_log (
    actor_id,
    actor_name,
    table_name,
    record_id,
    operation,
    changed_fields,
    old_data,
    new_data
  )
  values (
    v_actor_id,
    v_actor_name,
    tg_table_name,
    v_record_id,
    tg_op,
    v_changed_fields,
    v_old_data,
    v_new_data
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

revoke all on function public.datainduk_record_change() from public, anon, authenticated;

drop trigger if exists datainduk_audit_students on public.students;
create trigger datainduk_audit_students
  after insert or update or delete on public.students
  for each row execute function public.datainduk_record_change();

drop trigger if exists datainduk_audit_teachers on public.teachers;
create trigger datainduk_audit_teachers
  after insert or update or delete on public.teachers
  for each row execute function public.datainduk_record_change();

