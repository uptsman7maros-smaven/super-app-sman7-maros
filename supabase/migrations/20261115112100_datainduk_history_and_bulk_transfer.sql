create or replace function public.datainduk_move_students_to_class(
  p_source_academic_year_id uuid,
  p_source_class_id uuid,
  p_destination_class_id uuid,
  p_student_ids uuid[]
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_requested_count integer;
  v_eligible_count integer;
  v_source_year_id uuid;
  v_destination_year_id uuid;
  v_updated_count integer;
begin
  if not public.superapp_has_active_role(array['super_admin', 'operator']::text[]) then
    raise exception 'Akses pemindahan siswa tidak diizinkan.'
      using errcode = '42501';
  end if;

  if p_source_academic_year_id is null or p_source_class_id is null
    or p_destination_class_id is null
    or coalesce(cardinality(p_student_ids), 0) = 0
  then
    raise exception 'Tahun ajaran asal, kelas asal, kelas tujuan, dan siswa wajib dipilih.'
      using errcode = '22023';
  end if;

  if cardinality(p_student_ids) > 5000 then
    raise exception 'Pemindahan dibatasi maksimal 5.000 siswa per proses.'
      using errcode = '22023';
  end if;

  select count(distinct selected.id)
    into v_requested_count
  from unnest(p_student_ids) as selected(id);

  if v_requested_count <> cardinality(p_student_ids) then
    raise exception 'Daftar siswa mengandung ID duplikat.'
      using errcode = '22023';
  end if;

  if p_source_class_id = p_destination_class_id then
    raise exception 'Kelas tujuan harus berbeda dari kelas asal.'
      using errcode = '22023';
  end if;

  select class_row.academic_year_id
    into v_source_year_id
  from public.classes as class_row
  where class_row.id = p_source_class_id;

  if v_source_year_id is distinct from p_source_academic_year_id then
    raise exception 'Kelas asal tidak sesuai dengan tahun ajaran yang dipilih.'
      using errcode = '22023';
  end if;

  select class_row.academic_year_id
    into v_destination_year_id
  from public.classes as class_row
  where class_row.id = p_destination_class_id;

  if v_destination_year_id is null then
    raise exception 'Kelas tujuan tidak ditemukan.'
      using errcode = '22023';
  end if;

  select count(*)
    into v_eligible_count
  from public.students as student
  where student.id = any(p_student_ids)
    and student.class_id = p_source_class_id
    and upper(coalesce(student.status::text, '')) <> 'GRADUATED';

  if v_eligible_count <> v_requested_count then
    raise exception 'Sebagian siswa tidak terdaftar pada tahun ajaran asal atau berstatus lulus. Muat ulang pilihan siswa.'
      using errcode = '22023';
  end if;

  update public.students as student
  set class_id = p_destination_class_id,
      updated_at = clock_timestamp()
  where student.id = any(p_student_ids);

  get diagnostics v_updated_count = row_count;
  return v_updated_count;
end;
$$;

revoke all on function public.datainduk_move_students_to_class(uuid, uuid, uuid, uuid[])
  from public, anon;
grant execute on function public.datainduk_move_students_to_class(uuid, uuid, uuid, uuid[])
  to authenticated;
