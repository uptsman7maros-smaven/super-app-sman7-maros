-- Compatibility schema for the integrated vanilla eOSIS application.
CREATE TABLE IF NOT EXISTS public.pengaturan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_sekolah TEXT DEFAULT 'SMAN 7 MAROS',
  logo_url TEXT,
  pemilihan_aktif BOOLEAN DEFAULT TRUE,
  kop_nama_sekolah TEXT DEFAULT 'SMAN 7 MAROS',
  kop_subjudul TEXT DEFAULT 'PEMILIHAN KETUA DAN WAKIL KETUA OSIS',
  kop_alamat TEXT DEFAULT '',
  kop_kontak TEXT DEFAULT '',
  admin_username TEXT DEFAULT 'admin',
  admin_password TEXT DEFAULT 'admin123',
  masa_bakti_mulai DATE,
  masa_bakti_selesai DATE,
  ditetapkan_di TEXT DEFAULT '',
  tanggal_ditetapkan DATE,
  pembina_osis_nama TEXT DEFAULT '',
  pembina_osis_nip TEXT DEFAULT '',
  ketua_panitia_nama TEXT DEFAULT '',
  ketua_panitia_nisn TEXT DEFAULT '',
  kepala_sekolah_nama TEXT DEFAULT '',
  kepala_sekolah_nip TEXT DEFAULT ''
);

INSERT INTO public.pengaturan (nama_sekolah, admin_username, admin_password)
SELECT 'SMAN 7 MAROS', 'admin', 'admin123'
WHERE NOT EXISTS (SELECT 1 FROM public.pengaturan);

CREATE TABLE IF NOT EXISTS public.kelas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_kelas TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.siswa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nisn TEXT NOT NULL UNIQUE,
  nama TEXT,
  tgl_lahir DATE,
  kelas_id BIGINT REFERENCES public.kelas(id),
  jenis_kelamin TEXT,
  status_memilih BOOLEAN NOT NULL DEFAULT FALSE,
  waktu_memilih TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.kandidat (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  no_urut INTEGER NOT NULL UNIQUE,
  nama_ketua TEXT NOT NULL,
  nama_wakil TEXT NOT NULL,
  visi TEXT DEFAULT '',
  misi TEXT DEFAULT '',
  slogan TEXT DEFAULT '',
  foto_url TEXT,
  total_suara INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.suara (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kandidat_id BIGINT NOT NULL REFERENCES public.kandidat(id),
  siswa_id BIGINT NOT NULL REFERENCES public.siswa(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (siswa_id)
);

CREATE OR REPLACE FUNCTION public.get_public_settings()
RETURNS JSON LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT row_to_json(s) FROM (
    SELECT nama_sekolah, logo_url, pemilihan_aktif, kop_nama_sekolah, kop_subjudul,
           kop_alamat, kop_kontak, masa_bakti_mulai, masa_bakti_selesai,
           ditetapkan_di, tanggal_ditetapkan, pembina_osis_nama, pembina_osis_nip,
           ketua_panitia_nama, ketua_panitia_nisn, kepala_sekolah_nama, kepala_sekolah_nip
    FROM public.pengaturan ORDER BY id LIMIT 1
  ) s;
$$;

CREATE OR REPLACE FUNCTION public.admin_login(p_username TEXT, p_password TEXT)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.pengaturan WHERE admin_username = p_username AND admin_password = p_password);
$$;

CREATE OR REPLACE FUNCTION public.get_candidates()
RETURNS JSON LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT COALESCE(json_agg(row_to_json(k) ORDER BY k.no_urut), '[]'::json)
  FROM (SELECT * FROM public.kandidat) k;
$$;

CREATE OR REPLACE FUNCTION public.student_login(p_nisn TEXT, p_tgl_lahir TEXT)
RETURNS JSON LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_row JSON;
BEGIN
  SELECT json_build_object(
    'id', s.id, 'nisn', s.nisn, 'nama', s.nama, 'tgl_lahir', s.tgl_lahir,
    'nama_kelas', k.nama_kelas, 'status_memilih', s.status_memilih
  ) INTO v_row
  FROM public.siswa s LEFT JOIN public.kelas k ON k.id = s.kelas_id
  WHERE s.nisn = p_nisn AND s.tgl_lahir = p_tgl_lahir::date;
  IF v_row IS NULL THEN RAISE EXCEPTION 'NISN atau tanggal lahir tidak sesuai.'; END IF;
  RETURN v_row;
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_vote(p_nisn TEXT, p_tgl_lahir TEXT, p_kandidat_id BIGINT)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_siswa public.siswa%ROWTYPE; v_open BOOLEAN;
BEGIN
  SELECT * INTO v_siswa FROM public.siswa WHERE nisn = p_nisn AND tgl_lahir = p_tgl_lahir::date;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pemilih tidak ditemukan.'; END IF;
  SELECT pemilihan_aktif INTO v_open FROM public.pengaturan ORDER BY id LIMIT 1;
  IF NOT COALESCE(v_open, FALSE) THEN RAISE EXCEPTION 'Pemilihan sedang ditutup.'; END IF;
  IF v_siswa.status_memilih THEN RAISE EXCEPTION 'Hak suara sudah digunakan.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.kandidat WHERE id = p_kandidat_id) THEN RAISE EXCEPTION 'Kandidat tidak ditemukan.'; END IF;
  INSERT INTO public.suara(kandidat_id, siswa_id) VALUES (p_kandidat_id, v_siswa.id);
  UPDATE public.siswa SET status_memilih = TRUE, waktu_memilih = NOW() WHERE id = v_siswa.id;
  UPDATE public.kandidat SET total_suara = total_suara + 1 WHERE id = p_kandidat_id;
  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_voting_status(p_username TEXT, p_password TEXT, p_aktif BOOLEAN)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.admin_login(p_username, p_password) THEN RAISE EXCEPTION 'Akun admin salah.'; END IF;
  UPDATE public.pengaturan SET pemilihan_aktif = p_aktif;
  RETURN TRUE;
END;
$$;
