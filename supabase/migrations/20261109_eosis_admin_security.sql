CREATE OR REPLACE FUNCTION public.get_dashboard_stats(p_username TEXT, p_password TEXT)
RETURNS JSON LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.eosis_admin_call(p_username, p_password) THEN
    RAISE EXCEPTION 'Akun admin salah.';
  END IF;
  RETURN json_build_object(
    'total_siswa', (SELECT COUNT(*) FROM public.siswa),
    'sudah_memilih', (SELECT COUNT(*) FROM public.siswa WHERE status_memilih),
    'belum_memilih', (SELECT COUNT(*) FROM public.siswa WHERE NOT status_memilih),
    'total_suara', (SELECT COUNT(*) FROM public.suara)
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.get_voting_results(p_username TEXT, p_password TEXT)
RETURNS JSON LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.eosis_admin_call(p_username, p_password) THEN
    RAISE EXCEPTION 'Akun admin salah.';
  END IF;
  RETURN COALESCE(
    (SELECT json_agg(row_to_json(k) ORDER BY no_urut) FROM public.kandidat k),
    '[]'::json
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.reset_voting_results(p_username TEXT, p_password TEXT)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.eosis_admin_call(p_username, p_password) THEN
    RAISE EXCEPTION 'Akun admin salah.';
  END IF;
  DELETE FROM public.suara WHERE TRUE;
  UPDATE public.siswa SET status_memilih = FALSE, waktu_memilih = NULL WHERE TRUE;
  UPDATE public.kandidat SET total_suara = 0 WHERE TRUE;
  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_voting_status(
  p_username TEXT,
  p_password TEXT,
  p_aktif BOOLEAN
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.eosis_admin_call(p_username, p_password) THEN
    RAISE EXCEPTION 'Akun admin salah.';
  END IF;

  UPDATE public.pengaturan
  SET pemilihan_aktif = p_aktif
  WHERE id = (SELECT id FROM public.pengaturan ORDER BY id LIMIT 1);

  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_system_sync_status_v3(p_username TEXT, p_password TEXT)
RETURNS JSON LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.eosis_admin_call(p_username, p_password) THEN
    RAISE EXCEPTION 'Akun admin salah.';
  END IF;
  RETURN json_build_object(
    'database_connected', TRUE,
    'pengaturan', (SELECT COUNT(*) FROM public.pengaturan),
    'kelas', (SELECT COUNT(*) FROM public.kelas),
    'siswa', (SELECT COUNT(*) FROM public.siswa),
    'kandidat', (SELECT COUNT(*) FROM public.kandidat),
    'suara', (SELECT COUNT(*) FROM public.suara),
    'siswa_sudah_memilih', (SELECT COUNT(*) FROM public.siswa WHERE status_memilih),
    'total_suara_kandidat', (SELECT COALESCE(SUM(total_suara), 0) FROM public.kandidat),
    'sinkron_status', 'TERSINKRON',
    'checked_at', NOW()
  );
END;
$$;

-- Restore the default login only when no administrator account exists.
-- Existing custom credentials are never overwritten.
DO $$
DECLARE
  admin_count BIGINT;
BEGIN
  CREATE EXTENSION IF NOT EXISTS pgcrypto;

  CREATE TABLE IF NOT EXISTS public.admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

  EXECUTE 'SELECT COUNT(*) FROM public.admin_users' INTO admin_count;
  IF admin_count = 0 THEN
    INSERT INTO public.admin_users(username, password_hash)
    VALUES ('admin', crypt('admin123', gen_salt('bf')));
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name = 'pengaturan'
  ) THEN
    UPDATE public.pengaturan
    SET admin_username = 'admin', admin_password = 'admin123'
    WHERE id = (SELECT id FROM public.pengaturan ORDER BY id LIMIT 1)
      AND NULLIF(TRIM(COALESCE(admin_username, '')), '') IS NULL;
  END IF;
END;
$$;
